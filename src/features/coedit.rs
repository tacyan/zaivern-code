//! 🔒 衝突ゼロ証明 (後でマージが一撃で出来ることを言い切る) の**登録だけ**。
//! 実体は `src/coedit.rs`。
//!
//! このファイルを置くだけで機能が繋がる。`main.rs` の `mod` 一覧にも
//! `feature.rs` のレジストリにも触らない (build.rs が `src/features/*.rs` を
//! 走査して拾う)。
//!
//! ## なぜ `#[path]` で実体を引き込むのか
//!
//! 実体は CLAUDE.md の指示どおり `src/coedit.rs` に置いている。ただし
//! `src/<名前>.rs` をクレートへ入れるには通常 `main.rs` の `mod` 一覧へ
//! 1 行足す必要があり、**それはまさに並列ブランチが取り合う共有行**である。
//! `#[path]` を使うと、`main.rs` を 1 バイトも触らずに実体を
//! `crate::features::coedit::imp` として取り込める (`train` / `split` と同じ形)。
//!
//! 実体が要求する共有面は**ゼロ**: `app.rs` / `palette.rs` / `feature.rs` /
//! `config.rs` / `keybinds.rs` / `main.rs` / `build.rs` / `cli.rs` の
//! どれも触っていない。
//!
//! ## 姉妹機能との住み分け
//!
//! * `lease.rs` — 同じファイルを 2 人に触らせない (**起こさない**側)
//! * `split.rs` — 配る前に衝突し得ない担当表を作る (**予定**の側)
//! * `conflict.rs` — 近い行の衝突を先に見せる (**見せる**側)
//! * `train.rs` — 順番を決めて実際に流す (rebase。止まる回数を減らす側)
//! * `coedit.rs` — **実際に書かれた差分だけを見て「一撃で入る」と言い切る**側。
//!   立った証明の統合は作業ツリーを一度も触らず、最後に参照を 1 回だけ動かす。
//!
//! ## 統合担当への申し送り
//!
//! CLI (`zai coedit proof|merge|regions`) の入口は [`cli_main`] として
//! 公開してある。`src/cli.rs` は共有ファイルなので**こちらでは配線していない**
//! — サブコマンドの分岐へ次の 1 行を足すと繋がる:
//!
//! ```ignore
//! "coedit" => return Some(crate::features::coedit::cli_main(&args[1..])),
//! ```
//!
//! 打鍵は割り当てていない (`keybinds::BindAction` は固定長配列 + 件数検査の
//! 硬い共有面なので、機能ブランチ側から増やすと必ず衝突する)。
//! **欲しい打鍵は「証明パネルの開閉」1 つだけ**なので、要れば直列で入れてほしい。

#[path = "../coedit.rs"]
mod imp;

pub use imp::FEATURE;

/// `zai coedit <sub>` の入口。
///
/// **まだどこからも呼ばれていない。** `src/cli.rs` は並列ブランチが取り合う
/// 共有ファイルなので、こちらでは配線しない約束になっている
/// (上の「統合担当への申し送り」の 1 行で繋がる)。それまでは未使用の
/// 再エクスポートなので、`never used` を 1 件だけ黙らせる。
/// **配線が入ったらこの `allow` は消すこと** — 「作ったのに繋いでいない」の
/// 検出器を、これ以上潰さないため。
#[allow(unused_imports)]
pub use imp::cliface::cli_main;
